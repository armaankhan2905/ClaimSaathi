"""Encrypted file storage for uploaded documents.

Files are encrypted with Fernet (AES-128-CBC + HMAC) before they touch the disk and
stored under random names, so nothing readable is ever written.
"""

import secrets
from functools import lru_cache
from pathlib import Path

from cryptography.fernet import Fernet

from .config import get_settings


def _storage_dir() -> Path:
    d = Path(get_settings().storage_dir)
    d.mkdir(parents=True, exist_ok=True)
    return d


@lru_cache
def _fernet_for(key: str) -> Fernet:
    return Fernet(key.encode())


def _fernet() -> Fernet:
    key = get_settings().file_encryption_key
    if not key:
        key_file = _storage_dir() / ".dev-key"
        if not key_file.exists():
            key_file.write_text(Fernet.generate_key().decode())
        key = key_file.read_text().strip()
    return _fernet_for(key)


def save(data: bytes) -> str:
    """Encrypt and store `data`. Returns the storage key to keep in the database."""
    storage_key = f"{secrets.token_hex(16)}.bin"
    (_storage_dir() / storage_key).write_bytes(_fernet().encrypt(data))
    return storage_key


def load(storage_key: str) -> bytes:
    return _fernet().decrypt((_storage_dir() / _safe(storage_key)).read_bytes())


def delete(storage_key: str) -> None:
    (_storage_dir() / _safe(storage_key)).unlink(missing_ok=True)


def _safe(storage_key: str) -> str:
    # Keys are generated by save(); refuse anything that could escape the folder.
    if "/" in storage_key or "\\" in storage_key or ".." in storage_key:
        raise ValueError("bad storage key")
    return storage_key
